#!/usr/bin/env python3
"""Phase D: extend the 41-country, two-basket panel to 2019-2025.

Trade: Phase B panel trade (2021-2024) + cache/comtrade/phaseD (2019, 2020, 2025),
same reporters, partners, flow, and HS codes. Exogenous: processed_v4
(GDELT 2019-2025 from rev21_gdelt_features.py, GSCPI and weather from
rev21_exogenous_phaseD.py). Construction: fuse_dataset.build_fused_tables with
config_phaseD.yaml (= config_phaseB.yaml with analysis window 2019-01..2025-12).

Check (stops on failure): every Phase B row in 2021-04..2024-11 that has a
valid target in both panels is reproduced exactly (inbound, seven features,
contraction). Edge months legitimately differ: 2021-01..03 trade proxies now
see late-2020 history, and some previously undefined targets become defined.

Outputs: processed_v4/{semiconductor,consumer}/{nodes,edges}_monthly.csv,
processed_v4/combined_nodes_long.csv, processed_v4/build_summary.json.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))

import fuse_dataset as fd  # noqa: E402
from common import load_config, read_table  # noqa: E402
from ingest_comtrade_bilateral import _standardize_bilateral  # noqa: E402
from rev21_build_consumer_panel import same  # noqa: E402
from rev21_build_phaseB_panel import EXCLUDED, SEMI, phaseb_records  # noqa: E402

BASE = Path(__file__).resolve().parent
ROOT = BASE / "data/four_year_2021_2024"
V2, V3, V4 = ROOT / "processed_v2", ROOT / "processed_v3", ROOT / "processed_v4"


def write_config() -> dict:
    cfg = yaml.safe_load((BASE / "config_phaseB.yaml").read_text())
    cfg["analysis"]["start_date"], cfg["analysis"]["end_date"] = "2019-01-01", "2025-12-31"
    for k in ("weather", "gdelt_monthly_features", "nodes", "edges", "graph", "gscpi"):
        cfg["outputs"][k] = f"data/four_year_2021_2024/processed_v4/{Path(cfg['outputs'][k]).name}"
    cfg["outputs"]["country_universe"] = "data/four_year_2021_2024/processed_v3/country_universe.csv"
    (BASE / "config_phaseD.yaml").write_text("# Phase D (paper-21 revision): 41 countries, 2019-2025; generated by rev21_build_phaseD_panel.py\n"
                                              + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True))
    return load_config("config_phaseD.yaml")


def phased_records() -> pd.DataFrame:
    frames = []
    for path in sorted((ROOT / "cache/comtrade/phaseD").glob("reporter_*.json")):
        payload = json.loads(path.read_text())
        raw = pd.DataFrame(payload["response"]["data"])
        if raw.empty:
            continue
        for period, part in raw.groupby(raw["period"].astype(str)):
            frames.append(_standardize_bilateral(part.reset_index(drop=True), period, payload["downloaded_at"]))
    frame = pd.concat(frames, ignore_index=True)
    frame = frame[~frame["reporter_code"].astype(str).isin(EXCLUDED)]
    frame["commodity_code"] = frame["commodity_code"].astype(str)
    return frame.drop_duplicates(["month", "reporter_code", "partner_code", "commodity_code", "flow_code"])


def main() -> int:
    config = write_config()
    V4.mkdir(parents=True, exist_ok=True)
    b, d = phaseb_records(), phased_records()
    b["commodity_code"] = b["commodity_code"].astype(str)
    trades = {
        "semiconductor": pd.concat([read_table(ROOT / "processed/comtrade.csv"), b[b["commodity_code"].isin(SEMI)],
                                    d[d["commodity_code"].isin(SEMI)]], ignore_index=True),
        "consumer": pd.concat([read_table(V2 / "comtrade_consumer.csv"), b[~b["commodity_code"].isin(SEMI)],
                               d[~d["commodity_code"].isin(SEMI)]], ignore_index=True),
    }
    gdelt_monthly = read_table(V4 / "gdelt_monthly_features.csv")
    gdelt_monthly["month"] = gdelt_monthly["month"].astype(str)
    # GDELT published no daily files for 2025-06-14..2025-07-01, so the month-end
    # window of 2025-06 is empty. Volume and tone for that month are set to the mean
    # of the country's 2025-05 and 2025-07 values; the strike flag keeps what the
    # first half of June shows. The affected rows are flagged in the summary.
    wide = gdelt_monthly.set_index(["country", "month"])
    gap = gdelt_monthly["month"].eq("2025-06")
    for col in ("news_vol_7d", "neg_tone_frac_3d"):
        fill = [(wide.at[(c, "2025-05"), col] + wide.at[(c, "2025-07"), col]) / 2 for c in gdelt_monthly.loc[gap, "country"]]
        gdelt_monthly.loc[gap, col] = [round(v) if col == "news_vol_7d" else v for v in fill]
    exo = dict(gdelt=pd.DataFrame(), gdelt_monthly=gdelt_monthly,
               weather=read_table(V4 / "weather_daily.csv"), gscpi=read_table(V4 / "gscpi_monthly.csv"))
    cols = ["inbound_flow_usd", *fd.FEATURES, "contraction"]
    summary, longs = {"phase_d_records": int(len(d)),
                      "gdelt_gap": "2025-06 news volume/tone interpolated from 2025-05 and 2025-07 (no GDELT files 2025-06-14..07-01)"}, []
    for basket, trade in trades.items():
        nodes, edges = fd.build_fused_tables(config, trade, **exo)
        nodes["month"] = nodes["month"].astype(str)
        prev = read_table(V3 / basket / "nodes_monthly.csv")
        prev["month"] = prev["month"].astype(str)
        key = ["host_country_id", "month"]
        both = prev[prev["month"].between("2021-04", "2024-11") & prev["target_valid"].astype(bool)][key]
        new_rows = nodes.merge(both, on=key)
        old_rows = prev.merge(both, on=key)
        new_rows = new_rows[new_rows["target_valid"].astype(bool)]
        old_rows = old_rows.merge(new_rows[key], on=key)
        match = same(new_rows, old_rows, cols)
        print(f"{basket}: {nodes['host_country_id'].nunique()} countries x {nodes['month'].nunique()} months; "
              f"Phase B rows 2021-04..2024-11 reproduced: {match:.1%} of {len(old_rows)}")
        if match < 1.0:
            raise SystemExit(f"{basket}: Phase B rows not reproduced; stopping")
        out = V4 / basket
        out.mkdir(exist_ok=True)
        nodes.to_csv(out / "nodes_monthly.csv", index=False)
        edges.to_csv(out / "edges_monthly.csv", index=False)
        summary[basket] = {"rows": int(len(nodes)), "valid_targets": int(nodes["target_valid"].astype(bool).sum()),
                           "months": [nodes["month"].min(), nodes["month"].max()], "edges": int(len(edges)),
                           "phaseB_rows_reproduced": match,
                           "zero_inbound_by_year": nodes.assign(y=nodes["month"].str[:4]).groupby("y")["inbound_flow_usd"].apply(lambda s: int((s <= 0).sum())).to_dict()}
        longs.append(nodes.assign(basket=basket))
    long = pd.concat(longs, ignore_index=True)
    long["series_id"] = long["host_country_id"] + "|" + long["basket"]
    long.to_csv(V4 / "combined_nodes_long.csv", index=False)
    (V4 / "build_summary.json").write_text(json.dumps(summary, indent=2, default=str))
    print(json.dumps(summary, indent=2, default=str))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
